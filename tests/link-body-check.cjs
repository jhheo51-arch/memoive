const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const reader=require('../link-reader.js');
const data=require('../data-tools.js');
assert.equal(reader.publisherUrl('https://techblog.woowahan.com/26034/'),'https://techblog.woowahan.com/wp-json/wp/v2/posts/26034');
assert.equal(reader.publisherUrl('https://techblog.woowahan.com.evil.test/26034/'),'');
assert.equal(reader.youtubeVideoId('https://www.youtube.com/watch?v=Aj2a5Ru2vMA'),'Aj2a5Ru2vMA');
assert.equal(reader.youtubeVideoId('https://youtu.be/Aj2a5Ru2vMA'),'Aj2a5Ru2vMA');
assert.equal(reader.youtubeVideoId('https://www.youtube-nocookie.com/embed/Aj2a5Ru2vMA'),'Aj2a5Ru2vMA');
assert.equal(reader.youtubeVideoId('https://music.youtube.com/watch?v=Aj2a5Ru2vMA'),'Aj2a5Ru2vMA');
assert.equal(reader.youtubeVideoId('https://youtube.com.evil.test/watch?v=Aj2a5Ru2vMA'),'');
assert.equal(data.linkType('https://www.youtube-nocookie.com/embed/Aj2a5Ru2vMA'),'video');
assert.equal(data.linkType('https://music.youtube.com/watch?v=Aj2a5Ru2vMA'),'video');
assert.ok(reader.youtubeTranscriptUrls('Aj2a5Ru2vMA').at(-1).endsWith('/Aj2a5Ru2vMA.txt'));
const caption='[0:10] '+('오늘은 주문 과정을 단순하게 만드는 방법을 살펴봅니다. '.repeat(3));
const transcript=`# Transcript: 주문까지 3초\n\nSource video: https://www.youtube.com/watch?v=Aj2a5Ru2vMA\nLanguage: ko (auto-generated)\n\n## Transcript\n${caption}\n[0:30] 사용자가 꼭 필요한 정보만 확인하고 주문하도록 흐름을 줄였습니다.`;
const parsedTranscript=reader.parseYoutubeTranscript(transcript,'Aj2a5Ru2vMA');
assert.equal(parsedTranscript.method,'youtube-transcript');
assert.ok(parsedTranscript.content.includes('[0:10]'));
assert.ok(parsedTranscript.content.length<caption.length+80);
assert.throws(()=>reader.parseYoutubeTranscript(transcript,'aaaaaaaaaaa'));
assert.throws(()=>reader.parseYoutubeTranscript('# Transcript: 주문까지 3초\n## Transcript\n'+'화면 메뉴 '.repeat(100),'Aj2a5Ru2vMA'));
assert.throws(()=>reader.parseReaderText('Title: 보안 위배 접근 제한 페이지 1\nWarning: Target URL returned error 403: Forbidden\nMarkdown Content:\n'+'안내'.repeat(100),'https://example.com'));
assert.throws(()=>reader.parseReaderText('Title: Just a moment\nMarkdown Content:\n'+'challenge'.repeat(100),'https://example.com'));
const pdf=reader.parseReaderText('Title: \u0000\nPublished Time: Tue, 29 Sep 2026 05:43:05 GMT\nMarkdown Content:\n# 2026\n# 금융 업종 분석 리포트\n'+('금융 시장 분석 내용입니다. '.repeat(20)),'https://cdn.example.com/report.pdf');
assert.equal(pdf.title,'2026 금융 업종 분석 리포트');
const content=('저장할 본문입니다. '.repeat(2000))+'마지막 본문 보존';
const record={id:'test',title:'긴 기록',topics:[],sourceBody:content};
assert.equal(data.validateBackup(JSON.stringify({records:[record]})).records[0].sourceBody,content);
assert.ok(reader.summarize('문장이너무길어서선택기준에해당하지않는내용'.repeat(100),'제목').summary);
const app=fs.readFileSync(require.resolve('../app.js'),'utf8');
const scope={LinkReader:reader,safeHost:()=> 'example.com',publishedDate:x=>x,extractActions:()=>[]};
vm.createContext(scope);
vm.runInContext(app.split('\n').find(x=>x.startsWith('function applyArticle(')),scope);
const sample={id:'keep',thought:'내 생각 보존',topics:['내 주제'],url:'https://example.com'};
scope.applyArticle(sample,{title:'제목',content,published:'',method:'publisher'});
assert.equal(sample.sourceBody,content);
assert.equal(sample.thought,'내 생각 보존');
assert.deepEqual(sample.topics,['내 주제']);
assert.equal(sample.fetchStatus,'ready');
assert.equal(sample.bodyMethod,'publisher');
console.log('PASS: publisher route, blocked-page detection, full body backup, long-text fallback, thought/topic preservation');
