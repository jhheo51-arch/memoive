const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const read = name => fs.readFileSync(path.join(__dirname, '..', name), 'utf8');
const html = read('index.html'), app = read('app.js');
assert.ok(!html.includes('基本 5개'));
assert.ok(!html.includes('기본 5개와 제품 사례 3개는'));
assert.ok(html.includes('세 글을 미리 묶어 둔 개선 제안'));
assert.ok(html.includes('id="capture-storage-note" hidden'));
assert.ok(html.includes('기본 제공 자료만 사용한 결과물은 실제 사용 집계에서 제외'));
assert.ok(html.includes('브라우저 데이터 삭제·기기 분실'));
const notice = {hidden: true};
const element = {classList: {add() {}}};
const context = {state: {records: []}, DataTools: require('../data-tools.js'), $: selector => selector === '#capture-storage-note' ? notice : element};
vm.createContext(context);
vm.runInContext(app.match(/^function openSheet\(id\).*$/m)[0], context);
vm.runInContext("openSheet('#capture-sheet')", context);
assert.equal(notice.hidden, false);
context.state.records = [{id: 'example-test', isExample: true}];
vm.runInContext("openSheet('#capture-sheet')", context);
assert.equal(notice.hidden, false);
context.state.records.push({id: 'my-record', title: '내 기록'});
vm.runInContext("openSheet('#capture-sheet')", context);
assert.equal(notice.hidden, true);
assert.ok(app.includes("recordVisual(due,'record-symbol')"));
assert.ok(app.includes("DataTools.typeLabel(r.type)"));
console.log('PASS: contextual help, first-capture notice, examples, analytics and backup disclosures');
